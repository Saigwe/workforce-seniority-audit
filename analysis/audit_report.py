# %% [markdown]
# # Audit report: headcount and seniority as of 31 October 2026
#
# Reproducible from the warehouse: `python analysis/audit_report.py --db warehouse/workforce.duckdb --out analysis/audit_report.md`.
# Counts only. Synthetic data.

# %%
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb


def md_table(rows, cols):
    head = "| " + " | ".join(c for c, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(f(r) for _, f in cols) + " |\n" for r in rows)


def build(con) -> str:
    q = lambda s: con.execute(s).fetchall()
    out = ["# Audit report: headcount and seniority as of 31 October 2026\n",
           "Generated by `analysis/audit_report.py` from the gold marts. Counts only; no worker rows. Synthetic data; demo results.\n"]

    # %% 1. The question two ways
    b = q("select step_no, step, change, running_total from gold.rpt_headcount_bridge order by 1")
    out.append("## 1. How many workers did we have on 31 October 2026?\n")
    out.append(f"Counting history rows with an open end date gives **{b[0][3]:,}**. Applying effective dates and explicit rejections gives **{b[-1][3]:,}**.\n")
    out.append(md_table(b, [("#", lambda r: str(r[0])), ("Rule", lambda r: r[1]), ("Change", lambda r: f"{r[2]:+,}" if r[0] not in (1, 7) else ""), ("Count", lambda r: f"{r[3]:,}")]))
    out.append("\nThe largest correction is the fixed-term placements: they carry a real end date after 31 October, so a filter on blank "
               "end dates misses people who are employed that day.\n")

    # %% 2. Rejections and flags
    r = q("select reason_code, severity, reason, affected, unit, rate from gold.rpt_quality_summary order by severity desc, affected desc")
    t = q("select raw_rows, deduplicated_rows, exact_duplicate_rows from gold.rpt_quality_summary limit 1")[0]
    out.append(f"\n## 2. What was rejected and flagged\n\n{t[0]:,} history rows delivered; {t[2]:,} exact duplicates removed; {t[1]:,} checked.\n")
    out.append(md_table(r, [("Code", lambda x: f"`{x[0]}`"), ("Severity", lambda x: x[1]), ("Rule", lambda x: x[2]), ("Affected", lambda x: f"{x[3]:,} {x[4]}"), ("Rate", lambda x: f"{100 * x[5]:.2f}%")]))

    # %% 3. Seniority
    s = q("select tenure_band, workers, share from gold.rpt_tenure_bands order by 1")
    out.append("\n## 3. Seniority on 31 October 2026\n\nCompleted months of continuous service with the current employer (gaps up to 31 days bridged).\n")
    out.append(md_table(s, [("Band", lambda x: x[0][3:]), ("Workers", lambda x: f"{x[1]:,}"), ("Share", lambda x: f"{100 * x[2]:.1f}%")]))
    ins = [x for x in s if x[0].startswith("6.")]
    out.append(f"\n{ins[0][1] if ins else 0} workers hold a valid placement but have a rejected row elsewhere in their history, so their "
               "continuous service cannot be established. They are reported as insufficient evidence, not given a guessed start date.\n")

    # %% 4. Reconciliation and extracts
    rc = q("select cut, workers from gold.rpt_reconciliation")
    ex = q("select rows_a, rows_b, job_family_differs, home_region_differs, record_created_differs from gold.rpt_extract_comparison")[0]
    out.append("\n## 4. Reconciliation\n\n")
    out.append(md_table(rc, [("Cut", lambda x: x[0]), ("Workers", lambda x: f"{x[1]:,}")]))
    out.append(f"\nThe two worker-master extracts have the same header and {ex[0]:,} rows each, but are not identical: job family differs "
               f"for {ex[2]} workers. The later extract is used.\n")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="warehouse/workforce.duckdb")
    ap.add_argument("--out", default="analysis/audit_report.md")
    a = ap.parse_args()
    with duckdb.connect(a.db, read_only=True) as con:
        Path(a.out).write_text(build(con), encoding="utf-8", newline="\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
